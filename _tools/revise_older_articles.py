from pathlib import Path
import re

ROOT = Path(".")

def load(name):
    return (ROOT / name).read_text(encoding="utf-8")

def save(name, text):
    (ROOT / name).write_text(text, encoding="utf-8")

def sub_once(name, pattern, repl, flags=0, desc=""):
    s = load(name)
    ns, n = re.subn(pattern, repl, s, count=1, flags=flags)
    if n != 1:
        raise RuntimeError(f"{name}: replacement failed: {desc or pattern[:100]}")
    save(name, ns)

def replace_once(name, old, new, desc=""):
    s = load(name)
    if old not in s:
        raise RuntimeError(f"{name}: text not found: {desc or old[:100]}")
    save(name, s.replace(old, new, 1))

def replace_if(name, old, new):
    s = load(name)
    if old in s:
        save(name, s.replace(old, new, 1))

def set_title(name, title, seo_title=None):
    s = load(name)
    s, n1 = re.subn(r'(?m)^title:\s*".*?"\s*$', f'title: "{title}"', s, count=1)
    if n1 != 1:
        raise RuntimeError(f"{name}: front-matter title not found")
    seo_title = seo_title or f"{title}｜邹德虎 Dehu Zou"
    s, n2 = re.subn(r'(?m)^seo_title:\s*".*?"\s*$', f'seo_title: "{seo_title}"', s, count=1)
    if n2 != 1:
        raise RuntimeError(f"{name}: seo_title not found")
    s, n3 = re.subn(r'(?m)^# .+$', f'# {title}', s, count=1)
    if n3 != 1:
        raise RuntimeError(f"{name}: H1 not found")
    save(name, s)

def set_description(name, desc):
    s = load(name)
    safe = desc.replace('"', '\\"')
    s, n = re.subn(r'(?m)^description:\s*".*?"\s*$', f'description: "{safe}"', s, count=1)
    if n != 1:
        raise RuntimeError(f"{name}: description not found")
    save(name, s)

def insert_after_meta(name, html):
    s = load(name)
    if html in s:
        return
    pat = re.compile(r'(<div class="article-meta"[^>]*>.*?</div>\n)', re.S)
    m = pat.search(s)
    if not m:
        raise RuntimeError(f"{name}: article-meta not found")
    save(name, s[:m.end()] + html + "\n" + s[m.end():])

